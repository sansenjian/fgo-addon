func rotl(x uint32, n uint) uint32 { return x<<n | x>>(32-n) }

func tauA(x uint32) uint32 {
	return uint32(sm4Sbox[x>>24])<<24 | uint32(sm4Sbox[(x>>16)&0xff])<<16 |
		uint32(sm4Sbox[(x>>8)&0xff])<<8 | uint32(sm4Sbox[x&0xff])
}

func linear(x uint32) uint32 { return x ^ rotl(x, 2) ^ rotl(x, 10) ^ rotl(x, 18) ^ rotl(x, 24) }

func expandKey(key []byte) (rks [32]uint32) {
	var k [36]uint32
	for i := 0; i < 4; i++ {
		k[i] = binary.BigEndian.Uint32(key[i*4:]) ^ sm4Fk[i]
	}
	for i := 0; i < 32; i++ {
		k[i+4] = k[i] ^ linear(tauA(k[i+1]^k[i+2]^k[i+3]^sm4Ck[i]))
		rks[i] = k[i+4]
	}
	return
}

func cryptBlock(in []byte, rks [32]uint32, decrypt bool, out []byte) {
	var x [36]uint32
	for i := 0; i < 4; i++ {
		x[i] = binary.BigEndian.Uint32(in[i*4:])
	}
	for i := 0; i < 32; i++ {
		rk := rks[i]
		if decrypt {
			rk = rks[31-i]
		}
		x[i+4] = x[i] ^ tauA(x[i+1]^x[i+2]^x[i+3]^rk) // 轮函数只含 S盒，无 _7 线性变换（已与前端正密文对拍验证）
	}
	for i := 0; i < 4; i++ {
		binary.BigEndian.PutUint32(out[i*4:], x[35-i])
	}
}

// sm4EncryptToBase64 对应前端 Tr(): SM4-ECB + PKCS7, base64 输出
func sm4EncryptToBase64(plaintext string) string {
	data := []byte(plaintext)
	pad := 16 - len(data)%16
	buf := append(append([]byte{}, data...), bytes.Repeat([]byte{byte(pad)}, pad)...)
	rks := expandKey([]byte("FateGoAutoAddon2025")[:16]) // 前端 slice(0,16) 截断
	out := make([]byte, len(buf))
	for i := 0; i < len(buf); i += 16 {
		cryptBlock(buf[i:i+16], rks, false, out[i:i+16])
	}
	return base64.StdEncoding.EncodeToString(out)
}
